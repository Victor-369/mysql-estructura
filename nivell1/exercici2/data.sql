-- Llista quants productes de categoria 'Begudes' s'han venut en una determinada localitat.
select l.name as locality, p.name as Product, sum(col.quantity) as drinks_sold
from CustomerOrderLine col
    join Product p on p.product_id = col.product_id
    join CustomerOrder co on co.customer_order_id = col.customer_order_id
    join Customer c on c.customer_id = co.customer_id
    join Locality l on l.locality_id = c.locality_id
where p.product_type = 'drink'
    and l.name = 'Barcelona'
group by l.name, p.name;


-- Llista quantes comandes ha efectuat un determinat empleat/da.
select emp.first_name as Name, emp.surname as Surname, emp.tax_id as tax_id,
    count(co.customer_order_id) as total_orders
from Employee emp
    left join CustomerOrder co on co.delivery_employee_id = emp.employee_id
where emp.tax_id = '70950101T'
group by emp.employee_id, emp.first_name, emp.surname, emp.tax_id;
